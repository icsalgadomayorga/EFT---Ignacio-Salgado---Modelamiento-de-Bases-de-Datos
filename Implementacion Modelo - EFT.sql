-- 1. REGION

CREATE TABLE REGION (
    id_region NUMBER(5) NOT NULL,
    nombre VARCHAR2(100 CHAR) NOT NULL,

    CONSTRAINT REGION_PK
        PRIMARY KEY (id_region)
);


-- 2. NACIONALIDAD
-- IDENTITY: INICIO 210, INCREMENTO 2

CREATE TABLE NACIONALIDAD (
    id_nacionalidad NUMBER(5)
        GENERATED BY DEFAULT AS IDENTITY
        (START WITH 210 INCREMENT BY 2)
        NOT NULL,

    descripcion VARCHAR2(60 CHAR) NOT NULL,

    CONSTRAINT NACIONALIDAD_PK
        PRIMARY KEY (id_nacionalidad)
);


-- 3. GENERO

CREATE TABLE GENERO (
    id_genero NUMBER(5) NOT NULL,
    descripcion VARCHAR2(40 CHAR) NOT NULL,

    CONSTRAINT GENERO_PK
        PRIMARY KEY (id_genero)
);


-- 4. ESTADO_CIVIL

CREATE TABLE ESTADO_CIVIL (
    id_estado_civil NUMBER(5) NOT NULL,
    descripcion VARCHAR2(50 CHAR) NOT NULL,

    CONSTRAINT ESTADO_CIVIL_PK
        PRIMARY KEY (id_estado_civil)
);


-- 5. ASOCIACION

CREATE TABLE ASOCIACION (
    id_asociacion NUMBER(5) NOT NULL,
    nombre_asociacion VARCHAR2(120 CHAR) NOT NULL,
    fecha_creacion DATE NOT NULL,
    tipo_asociacion VARCHAR2(1 CHAR) NOT NULL,

    CONSTRAINT ASOCIACION_PK
        PRIMARY KEY (id_asociacion),

    CONSTRAINT ASOCIACION_FECHA_CK
        CHECK (fecha_creacion >= DATE '1980-12-31'),

    CONSTRAINT ASOCIACION_TIPO_CK
        CHECK (tipo_asociacion IN ('P', 'A'))
);


-- 6. ESCUELA_FUTBOL

CREATE TABLE ESCUELA_FUTBOL (
    id_escuela NUMBER(5) NOT NULL,
    nombre_escuela VARCHAR2(100 CHAR) NOT NULL,
    capacidad NUMBER(8) NOT NULL,
    fecha_fundacion DATE NOT NULL,

    CONSTRAINT ESCUELA_FUTBOL_PK
        PRIMARY KEY (id_escuela),

    CONSTRAINT ESCUELA_CAPACIDAD_CK
        CHECK (capacidad >= 0)
);


-- 7. IDIOMA

CREATE TABLE IDIOMA (
    id_idioma NUMBER(5) NOT NULL,
    nombre_idioma VARCHAR2(60 CHAR) NOT NULL,

    CONSTRAINT IDIOMA_PK
        PRIMARY KEY (id_idioma)
);


-- ============================================================
-- PARTE 2: SECUENCIA Y TABLA CLUB_FUTBOL
-- ============================================================

-- SECUENCIA DESDE 703, INCREMENTO DE 4

CREATE SEQUENCE SEQ_CLUB_FUTBOL
    START WITH 703
    INCREMENT BY 4
    NOCYCLE
    NOCACHE;


-- 8. CLUB_FUTBOL

CREATE TABLE CLUB_FUTBOL (
    id_club NUMBER(5)
        DEFAULT SEQ_CLUB_FUTBOL.NEXTVAL NOT NULL,

    nombre_club VARCHAR2(100 CHAR) NOT NULL,
    patrimonio NUMBER(15,2) NOT NULL,
    ubicacion_calle VARCHAR2(150 CHAR) NOT NULL,
    tipo_club VARCHAR2(30 CHAR) NOT NULL,

    CONSTRAINT CLUB_FUTBOL_PK
        PRIMARY KEY (id_club),

    CONSTRAINT CLUB_FUTBOL_NOMBRE_UN
        UNIQUE (nombre_club),

    CONSTRAINT CLUB_PATRIMONIO_CK
        CHECK (patrimonio >= 0)
);


-- ============================================================
-- PARTE 3: TABLAS DEPENDIENTES
-- ============================================================


-- 9. COMUNA

CREATE TABLE COMUNA (
    id_comuna NUMBER(5) NOT NULL,
    nombre VARCHAR2(100 CHAR) NOT NULL,
    REGION_id_region NUMBER(5) NOT NULL,

    CONSTRAINT COMUNA_PK
        PRIMARY KEY (id_comuna),

    CONSTRAINT COMUNA_REGION_FK
        FOREIGN KEY (REGION_id_region)
        REFERENCES REGION(id_region)
);


-- 10. TRABAJADOR
-- SUPERTIPO DE JUGADOR Y PERSONAL_PLANTA

CREATE TABLE TRABAJADOR (
    cod_inscripcion NUMBER(10) NOT NULL,
    rut NUMBER(8) NOT NULL,
    digito_verificador VARCHAR2(1 CHAR) NOT NULL,
    nombres VARCHAR2(100 CHAR) NOT NULL,
    apellidos VARCHAR2(100 CHAR) NOT NULL,
    sueldo_base NUMBER(12,2) NOT NULL,
    fecha_nacimiento DATE NOT NULL,
    telefono_movil VARCHAR2(20 CHAR) NOT NULL,
    direccion VARCHAR2(150 CHAR) NOT NULL,

    COMUNA_id_comuna NUMBER(5) NOT NULL,
    GENERO_id_genero NUMBER(5) NOT NULL,
    ESTADO_CIVIL_id_estado_civil NUMBER(5) NOT NULL,
    NACIONALIDAD_id_nacionalidad NUMBER(5) NOT NULL,

    CONSTRAINT TRABAJADOR_PK
        PRIMARY KEY (cod_inscripcion),

    CONSTRAINT TRABAJADOR_RUT_UN
        UNIQUE (rut, digito_verificador),

    CONSTRAINT TRABAJADOR_SUELDO_CK
        CHECK (sueldo_base >= 0),

    CONSTRAINT TRABAJADOR_COMUNA_FK
        FOREIGN KEY (COMUNA_id_comuna)
        REFERENCES COMUNA(id_comuna),

    CONSTRAINT TRABAJADOR_GENERO_FK
        FOREIGN KEY (GENERO_id_genero)
        REFERENCES GENERO(id_genero),

    CONSTRAINT TRABAJADOR_ESTADO_CIVIL_FK
        FOREIGN KEY (ESTADO_CIVIL_id_estado_civil)
        REFERENCES ESTADO_CIVIL(id_estado_civil),

    CONSTRAINT TRABAJADOR_NACIONALIDAD_FK
        FOREIGN KEY (NACIONALIDAD_id_nacionalidad)
        REFERENCES NACIONALIDAD(id_nacionalidad)
);


-- 11. JUGADOR
-- SUBTIPO DE TRABAJADOR

CREATE TABLE JUGADOR (
    cod_inscripcion NUMBER(10) NOT NULL,
    puesto VARCHAR2(60 CHAR) NOT NULL,
    premios_acumulados NUMBER(12,2) NOT NULL,
    anio_fin_amateurismo NUMBER(4),

    ASOCIACION_id_asociacion NUMBER(5) NOT NULL,
    ESCUELA_FUTBOL_id_escuela NUMBER(5),

    CONSTRAINT JUGADOR_PK
        PRIMARY KEY (cod_inscripcion),

    CONSTRAINT JUGADOR_TRABAJADOR_FK
        FOREIGN KEY (cod_inscripcion)
        REFERENCES TRABAJADOR(cod_inscripcion),

    CONSTRAINT JUGADOR_ASOCIACION_FK
        FOREIGN KEY (ASOCIACION_id_asociacion)
        REFERENCES ASOCIACION(id_asociacion),

    CONSTRAINT JUGADOR_ESCUELA_FUTBOL_FK
        FOREIGN KEY (ESCUELA_FUTBOL_id_escuela)
        REFERENCES ESCUELA_FUTBOL(id_escuela),

    CONSTRAINT JUGADOR_PREMIOS_CK
        CHECK (premios_acumulados >= 0)
);


-- 12. PERSONAL_PLANTA
-- SUBTIPO DE TRABAJADOR

CREATE TABLE PERSONAL_PLANTA (
    cod_inscripcion NUMBER(10) NOT NULL,
    horas_trabajadas NUMBER(6,2),
    valor_horas_extras NUMBER(12,2),
    CLUB_FUTBOL_id_club NUMBER(5) NOT NULL,

    CONSTRAINT PERSONAL_PLANTA_PK
        PRIMARY KEY (cod_inscripcion),

    CONSTRAINT PERSONAL_PLANTA_TRABAJADOR_FK
        FOREIGN KEY (cod_inscripcion)
        REFERENCES TRABAJADOR(cod_inscripcion),

    CONSTRAINT PERSONAL_PLANTA_CLUB_FUTBOL_FK
        FOREIGN KEY (CLUB_FUTBOL_id_club)
        REFERENCES CLUB_FUTBOL(id_club),

    CONSTRAINT PERSONAL_HORAS_CK
        CHECK (horas_trabajadas >= 0),

    CONSTRAINT PERSONAL_EXTRAS_CK
        CHECK (valor_horas_extras >= 0)
);


-- 13. JUGADOR_IDIOMA
-- CLAVE PRIMARIA COMPUESTA

CREATE TABLE JUGADOR_IDIOMA (
    nivel_dominio VARCHAR2(30 CHAR) NOT NULL,
    JUGADOR_cod_inscripcion NUMBER(10) NOT NULL,
    IDIOMA_id_idioma NUMBER(5) NOT NULL,

    CONSTRAINT JUGADOR_IDIOMA_PK
        PRIMARY KEY (
            JUGADOR_cod_inscripcion,
            IDIOMA_id_idioma
        ),

    CONSTRAINT JUGADOR_IDIOMA_JUGADOR_FK
        FOREIGN KEY (JUGADOR_cod_inscripcion)
        REFERENCES JUGADOR(cod_inscripcion),

    CONSTRAINT JUGADOR_IDIOMA_IDIOMA_FK
        FOREIGN KEY (IDIOMA_id_idioma)
        REFERENCES IDIOMA(id_idioma)
);


-- 14. HISTORIAL_CLUB

CREATE TABLE HISTORIAL_CLUB (
    id_historial NUMBER(10) NOT NULL,
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE,

    JUGADOR_cod_inscripcion NUMBER(10) NOT NULL,
    CLUB_FUTBOL_id_club NUMBER(5) NOT NULL,

    CONSTRAINT HISTORIAL_CLUB_PK
        PRIMARY KEY (id_historial),

    CONSTRAINT HISTORIAL_CLUB_JUGADOR_FK
        FOREIGN KEY (JUGADOR_cod_inscripcion)
        REFERENCES JUGADOR(cod_inscripcion),

    CONSTRAINT HISTORIAL_CLUB_CLUB_FUTBOL_FK
        FOREIGN KEY (CLUB_FUTBOL_id_club)
        REFERENCES CLUB_FUTBOL(id_club),

    CONSTRAINT HISTORIAL_CLUB_FECHAS_CK
        CHECK (
            fecha_fin IS NULL
            OR fecha_fin >= fecha_inicio
        )
);


