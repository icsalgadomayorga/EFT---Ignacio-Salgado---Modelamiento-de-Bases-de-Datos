-- CONSULTAS DE RECUPERACION DE INFORMACION
-- ============================================================


-- ============================================================
-- INFORME 1
-- ASOCIACIONES PROFESIONALES CREADAS DESPUES DE 2000
-- ============================================================

SELECT
    'ID:' || id_asociacion || ' * ' ||
        nombre_asociacion AS asociacion,

    TO_CHAR(fecha_creacion, 'DD-MM-YYYY') AS creada,

    tipo_asociacion AS tipo

FROM ASOCIACION

WHERE tipo_asociacion = 'P'
  AND fecha_creacion >= DATE '2001-01-01'

ORDER BY fecha_creacion DESC;


-- ============================================================
-- INFORME 2
-- PATRIMONIO DE CLUBES EN PESOS Y DOLARES
-- TIPO DE CAMBIO: 955 PESOS POR DOLAR
-- ============================================================

SELECT
    id_club AS club,

    nombre_club AS "NOMBRE CLUB",

    patrimonio AS "PATRIMONIO EN PESOS",

    ROUND(patrimonio / 955, 2)
        AS "PATRIMONIO EN DOLARES"

FROM CLUB_FUTBOL

WHERE UPPER(nombre_club) LIKE '%A%'
  AND patrimonio > 200000000
  AND tipo_club = 'Profesional'

ORDER BY id_club DESC;


